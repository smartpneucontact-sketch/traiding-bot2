# ───── (a) default off: byte-identical to the pre-change engine ───────────
def test_a_default_off():
    print("\n[a] delist_exit=False (default) is byte-identical to pre-change engine")
    idx, close, opn, w, lq = build_panel()

    cfg = BTConfigV2()
    check("BTConfigV2 defaults off",
          cfg.delist_exit is False and cfg.delist_haircut_pct == 0.0)

    runs = {
        "next_open": run_backtest_v2(w, close, BTConfigV2(exec_model="next_open"),
                                     open_prices=opn),
        "next_close": run_backtest_v2(w, close, BTConfigV2(exec_model="next_close")),
    }

    check("pristine capture embedded", PRISTINE_B64 is not None)
    pristine = pickle.loads(base64.b64decode(PRISTINE_B64))
    for model, bt in runs.items():
        p = pristine[model]
        check(f"{model}: returns byte-identical to pre-change engine",
              np.array_equal(bt["returns"].to_numpy(), p["returns"].to_numpy())
              and bt["returns"].index.equals(p["returns"].index))
        check(f"{model}: equity byte-identical",
              np.array_equal(bt["equity"].to_numpy(), p["equity"].to_numpy()))
        for k, v in p["summary"].items():
            check(f"{model}: summary[{k}] exact", bt["summary"][k] == v,
                  f"new={bt['summary'][k]!r} pristine={v!r}")
        check(f"{model}: no delist keys added to default summary",
              "delist_exit" not in bt["summary"]
              and "n_delist_exits" not in bt["summary"])

    # last_quote passed but hook off → ignored, byte-identical.
    bt_lq = run_backtest_v2(w, close, BTConfigV2(exec_model="next_close"),
                            last_quote=lq)
    check("last_quote ignored when delist_exit=False (byte-identical)",
          np.array_equal(bt_lq["returns"].to_numpy(),
                         runs["next_close"]["returns"].to_numpy())
          and np.array_equal(bt_lq["equity"].to_numpy(),
                             runs["next_close"]["equity"].to_numpy()))

    # Pin the documented silent behavior: dead name holds weight at 0 return.
    eff = runs["next_close"]["weights"]
    check("silent: dead BANKR keeps 0.5 effective weight forever",
          bool((eff["BANKR"].iloc[BANKR_LAST + 1:] == 0.5).all()))
    check("silent: gross stays 2.0 after death (cap still deflated)",
          np.isclose(eff.abs().sum(axis=1).iloc[-1], 2.0))

    # Guard rails: misuse raises instead of silently no-opping.
    try:
        run_backtest_v2(w, close, BTConfigV2(delist_exit=True))
        check("delist_exit without last_quote raises", False)
    except ValueError:
        check("delist_exit without last_quote raises", True)
    try:
        run_backtest_v2(w, close,
                        BTConfigV2(delist_exit=True, exec_model="legacy_period"),
                        last_quote=lq)
        check("delist_exit under legacy_period raises", False)
    except ValueError:
        check("delist_exit under legacy_period raises", True)


# ───── (b) hook on: exit at last quoted close, tc charged, gross freed ────
def test_b_hook_on():
    print("\n[b] delist_exit=True: exit at last quoted close, tc, gross freed")
    idx, close, opn, w, lq = build_panel()
    cfg0 = BTConfigV2(exec_model="next_close", tc_bps=0.0, delist_exit=True)
    bt = run_backtest_v2(w, close, cfg0, last_quote=lq)
    eff, r = bt["weights"], bt["returns"]
    exit_day = idx[BANKR_LAST + 1]

    # Held through the last quoted close, zero from the day after — forever,
    # even past the day-285 re-assertion of 0.6 by the naive selector.
    check("held at last quoted close (eff 0.5 on lq day)",
          eff.at[idx[BANKR_LAST], "BANKR"] == 0.5)
    check("eff = 0 from day after last quote, permanently",
          bool((eff["BANKR"].loc[exit_day:] == 0.0).all()))
    check("ACQ exits one day after ITS last quote",
          eff.at[idx[ACQ_LAST], "ACQ"] > 0.0
          and bool((eff["ACQ"].loc[idx[ACQ_LAST + 1]:] == 0.0).all()))

    # Gross frees up: cap (2.0 < 2.4) deflated all names to 0.5; after BANKR
    # dies gross target = 1.8 → survivors rise to their full 0.6.
    check("gross freed for survivors on exit day",
          eff.at[exit_day, "LIVE1"] == 0.6 and eff.at[exit_day, "LIVE2"] == 0.6
          and eff.at[exit_day, "ACQ"] == 0.6)
    check("exit trade in turnover (Δ BANKR = -0.5 on exit day)",
          np.isclose(eff.diff().at[exit_day, "BANKR"], -0.5))

    # tc charged on the exit turnover like any sell:
    # |Δ| on exit day = 0.5 (BANKR out) + 3×0.1 (cap release) = 0.8.
    bt_tc = run_backtest_v2(
        w, close, BTConfigV2(exec_model="next_close", tc_bps=100.0,
                             delist_exit=True), last_quote=lq)
    tc_paid = r.loc[exit_day] - bt_tc["returns"].loc[exit_day]
    check("tc charged on exit-day turnover 0.8 @100bp",
          np.isclose(tc_paid, 0.8 * 100.0 / 10_000.0, atol=1e-12),
          f"got {tc_paid:.6e}")

    # Returns identical to the DEFAULT engine through the last quoted close
    # (the hook only changes the book from the day after).
    bt_def = run_backtest_v2(w, close, BTConfigV2(exec_model="next_close",
                                                  tc_bps=0.0))
    check("returns unchanged through last quoted close",
          np.array_equal(r.loc[:idx[BANKR_LAST]].to_numpy(),
                         bt_def["returns"].loc[:idx[BANKR_LAST]].to_numpy()))

    # Equivalence: hook == manually zeroing the daily weights from each
    # last-quote date onward (the mask composes exactly like apply_gate).
    manual = expand_daily(w, idx)
    manual.loc[idx[BANKR_LAST]:, "BANKR"] = 0.0
    manual.loc[idx[ACQ_LAST]:, "ACQ"] = 0.0
    bt_man = run_backtest_v2(manual, close,
                             BTConfigV2(exec_model="next_close", tc_bps=0.0),
                             weights_are_daily=True)
    check("hook == manual weight zeroing (byte-identical returns)",
          np.array_equal(r.to_numpy(), bt_man["returns"].to_numpy()))

    # Dead name cannot leak: garbage post-death prices change NOTHING with
    # the hook on (and provably would corrupt the default engine).
    close_g = close.copy()
    close_g.loc[idx[BANKR_LAST + 1]:, "BANKR"] = 1e6
    bt_g = run_backtest_v2(w, close_g, cfg0, last_quote=lq)
    check("subsequent returns unaffected by dead name (garbage-price test)",
          np.array_equal(r.to_numpy(), bt_g["returns"].to_numpy()))
    bt_g_def = run_backtest_v2(w, close_g, BTConfigV2(exec_model="next_close",
                                                      tc_bps=0.0))
    check("(control) default engine IS corrupted by the same garbage",
          not np.allclose(bt_def["returns"].to_numpy(),
                          bt_g_def["returns"].to_numpy()))

    # Provenance + next_open smoke (same effective book, finite returns).
    check("summary provenance: delist_exit / n_delist_exits",
          bt["summary"].get("delist_exit") is True
          and bt["summary"].get("n_delist_exits") == 2)
    bt_no = run_backtest_v2(w, close,
                            BTConfigV2(exec_model="next_open", tc_bps=0.0,
                                       delist_exit=True),
                            open_prices=opn, last_quote=lq)
    check("next_open: same effective book, finite returns",
          np.array_equal(bt_no["weights"].to_numpy(), eff.to_numpy())
          and np.isfinite(bt_no["returns"].to_numpy()).all()
          and bt_no["weights"].at[exit_day, "BANKR"] == 0.0)


# ───── (c) haircut arm: -30% on the bankruptcy exit day only ──────────────
def test_c_haircut():
    print("\n[c] delist_haircut_pct: -30% exactly on the bankruptcy exit day")
    idx, close, opn, w, lq = build_panel()
    kw = dict(exec_model="next_close", tc_bps=0.0, delist_exit=True)
    r0 = run_backtest_v2(w, close, BTConfigV2(**kw), last_quote=lq)["returns"]
    bt_h = run_backtest_v2(w, close,
                           BTConfigV2(delist_haircut_pct=0.30, **kw),
                           last_quote=lq)
    diff = bt_h["returns"] - r0

    bankr_exit = idx[BANKR_LAST + 1]
    acq_exit = idx[ACQ_LAST + 1]
    # BANKR terminal 4.0 < 20% of its 252d-ago close (~80.7) → bankruptcy
    # class; exited effective weight 0.5 → extra return −0.30 × 0.5 = −0.15.
    check("-0.30 × 0.5 exited weight hits the exit day",
          np.isclose(diff.loc[bankr_exit], -0.30 * 0.5, atol=1e-15),
          f"got {diff.loc[bankr_exit]:.6f}")
    check("haircut hits ONLY that day (all other days byte-identical)",
          np.array_equal(diff.drop(bankr_exit).to_numpy(),
                         np.zeros(len(diff) - 1)))
    # ACQ terminal 130 vs ~102.6 a year prior → NOT bankruptcy class.
    check("acquisition-class exit day NOT haircut",
          diff.loc[acq_exit] == 0.0, f"got {diff.loc[acq_exit]:.6e}")
    check("summary provenance: delist_haircut_pct",
          bt_h["summary"].get("delist_haircut_pct") == 0.30)


