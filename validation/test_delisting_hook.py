# ───── synthetic panel: one bankruptcy, one acquisition, two survivors ────
N_DAYS = 300
BANKR_LAST = 270   # index position of BANKR's last quoted day
ACQ_LAST = 280     # index position of ACQ's last quoted day


def build_panel():
    """4-name close/open panel + sparse weights + last_quote series.

    BANKR : log-linear collapse 100 → 4 over 271 quoted days; terminal 4 is
            ~5% of its close 252 trading days earlier (~80.7) → bankruptcy
            class under the prereg's <20% rule.
    ACQ   : log-linear rise 100 → 130 over 281 quoted days; terminal 130 is
            ~127% of its 252d-ago close (~102.6) → NOT bankruptcy class.
    Both go NaN after their last quoted day (the documented Norgate export
    behavior: series simply end).
    Weights: 0.6 in each of the 4 names decided on day 0 and re-asserted on
    day 285 (AFTER both deaths — a naive selector re-picking dead names, so
    the hook must override re-assignment too). Gross 2.4 > cap 2.0 → the cap
    binds at 5/6 while all four are alive (effective 0.5 each).
    """
    idx = pd.bdate_range("2023-01-02", periods=N_DAYS)

    def walk(start, drift, vol, seed):
        r = np.random.RandomState(seed).normal(drift, vol, N_DAYS)
        r[0] = 0.0
        return start * np.exp(np.cumsum(r))

    close = pd.DataFrame(
        {"LIVE1": walk(100.0, 4e-4, 0.010, 1),
         "LIVE2": walk(80.0, 2e-4, 0.012, 2),
         "BANKR": np.nan, "ACQ": np.nan},
        index=idx,
    )
    close.iloc[: BANKR_LAST + 1, close.columns.get_loc("BANKR")] = np.exp(
        np.linspace(np.log(100.0), np.log(4.0), BANKR_LAST + 1))
    close.iloc[: ACQ_LAST + 1, close.columns.get_loc("ACQ")] = np.exp(
        np.linspace(np.log(100.0), np.log(130.0), ACQ_LAST + 1))

    opn = (close.shift(1) + close) / 2.0
    opn.iloc[0] = close.iloc[0] * 0.999

    w = pd.DataFrame([[0.6] * 4, [0.6] * 4],
                     index=[idx[0], idx[285]], columns=close.columns)
    last_quote = pd.Series({"BANKR": idx[BANKR_LAST], "ACQ": idx[ACQ_LAST]})
    return idx, close, opn, w, last_quote


